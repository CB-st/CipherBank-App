using CipherBank_app.E2ETests.Support;
using FluentAssertions;
using Xunit;

namespace CipherBank_app.E2ETests.Tests;

/// <summary>
/// Exercises recovery-export name validation and command construction on the host.
/// Use: High (CI and local). Scope: E2E recovery-export cleanup.
/// </summary>
public class DeviceExportNamesTests
{
    private const string DeviceDir = "/sdcard/Download";
    private const string ValidName = "cipherbank-recovery-20261120-091500.cbr.json";

    /// <summary>
    /// Verifies that validation accepts the filename format generated by the app.
    /// Use: High (CI and local). Scope: recovery-export name validation.
    /// </summary>
    [Theory]
    [InlineData(ValidName)]
    public void IsGeneratedExportName_WithGeneratedName_ReturnsTrue(string name) =>
        DeviceExportNames.IsGeneratedExportName(name).Should().BeTrue();

    /// <summary>
    /// Verifies that both validation and command construction reject names outside the generated format.
    /// Use: High (CI and local). Scope: device listing and cleanup operands.
    /// </summary>
    [Theory]
    [InlineData("cipherbank-recovery-20261120-091500;reboot;.cbr.json")]
    [InlineData("cipherbank-recovery-20261120-091500$(reboot).cbr.json")]
    [InlineData("cipherbank-recovery-20261120-091500`reboot`.cbr.json")]
    [InlineData("cipherbank-recovery-20261120-091500 .cbr.json")]
    [InlineData(" " + ValidName)]
    [InlineData(ValidName + " ")]
    [InlineData("cipherbank-recovery-20261120-091500'.cbr.json")]
    [InlineData("cipherbank-recovery-20261120-091500\".cbr.json")]
    [InlineData(ValidName + "\nreboot")]
    [InlineData(ValidName + "\n")]
    [InlineData(ValidName + "\r")]
    [InlineData(ValidName + "\t")]
    [InlineData("-rf")]
    [InlineData("-" + ValidName)]
    [InlineData("../x")]
    [InlineData("a/b")]
    [InlineData("../" + ValidName)]
    [InlineData("Cipherbank-recovery-20261120-091500.cbr.json")]
    [InlineData("cipherbank-recovery-20261120-091500.cbr.JSON")]
    [InlineData("cipherbank-recovery-2026112-091500.cbr.json")]
    [InlineData("cipherbank-recovery-20261120-0915000.cbr.json")]
    [InlineData("cipherbank-recovery-٢0261120-091500.cbr.json")]
    [InlineData(null)]
    [InlineData("")]
    public void GeneratedExportNameBoundary_WithInvalidName_RejectsName(string? name)
    {
        DeviceExportNames.IsGeneratedExportName(name).Should().BeFalse();

        Action buildCommand = () => DeviceExportNames.BuildRemoveCommand(DeviceDir, name);
        buildCommand.Should().Throw<ArgumentException>().WithParameterName(nameof(name));
    }

    /// <summary>
    /// Verifies the exact shell quoting of ordinary text and shell syntax.
    /// Use: High (CI and local). Scope: one shell operand.
    /// </summary>
    [Theory]
    [InlineData("plain", "'plain'")]
    [InlineData("a'b", "'a'\\''b'")]
    [InlineData("$(value)", "'$(value)'")]
    [InlineData("`value`", "'`value`'")]
    [InlineData("a;b", "'a;b'")]
    [InlineData("a\nb", "'a\nb'")]
    [InlineData("-rf", "'-rf'")]
    public void PosixSingleQuote_WithShellText_ReturnsExactQuotedWord(string value, string expected) =>
        DeviceExportNames.PosixSingleQuote(value).Should().Be(expected);

    /// <summary>
    /// Verifies that an embedded NUL cannot be emitted into a command.
    /// Use: High (CI and local). Scope: one shell operand.
    /// </summary>
    [Fact]
    public void PosixSingleQuote_WithNul_ThrowsArgumentException()
    {
        Action quote = () => DeviceExportNames.PosixSingleQuote("a\0b");
        quote.Should().Throw<ArgumentException>().WithParameterName("value");
    }

    /// <summary>
    /// Verifies that a removal command quotes the entire path and ends option parsing before it.
    /// Use: High (CI and local). Scope: device cleanup command text.
    /// </summary>
    [Theory]
    [InlineData(DeviceDir, "rm -f -- '/sdcard/Download/" + ValidName + "'")]
    [InlineData("/sdcard/Owner's Downloads", "rm -f -- '/sdcard/Owner'\\''s Downloads/" + ValidName + "'")]
    public void BuildRemoveCommand_WithGeneratedName_ReturnsExactCommand(string deviceDir, string expected) =>
        DeviceExportNames.BuildRemoveCommand(deviceDir, ValidName).Should().Be(expected);

    /// <summary>
    /// Verifies that a mixed listing keeps only matching filenames and preserves their order.
    /// Use: High (CI and local). Scope: device listing filter.
    /// </summary>
    [Fact]
    public void FilterGeneratedExportNames_WithMixedListing_KeepsMatchingNamesInOrder()
    {
        const string OlderName = "cipherbank-recovery-20261119-231500.cbr.json";
        string[] names = ["other.txt", ValidName, " " + ValidName, OlderName + "?reboot", OlderName, string.Empty];

        DeviceExportNames.FilterGeneratedExportNames(names).Should().Equal(ValidName, OlderName);
    }
}
